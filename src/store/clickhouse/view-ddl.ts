// cspell:ignore clickhouse subquery subqueries inlines seqs
/**
 * The DDL of the visibility gate views, generated from the one TypeScript
 * definition the API compiler inlines (`pinnedViewDefinitions`,
 * `pinnedGateTerms` in visibility.ts):
 * - `ddl/050_views.sql`: every `*_at` view and its `*_v` twin, plus `node_v`;
 * - the `spend_at` / `authchain_link_at` statements of 070/080.
 *
 * `yarn clickhouse:views:generate` (view-ddl-cli.ts) rewrites 050 from this
 * module; `view-ddl.spec.ts` fails when a committed file differs from the
 * generated text, so a gate change is made in one place.
 */
import type { PinnedViewDefinition } from './visibility.js';
import { pinnedGateTerms, pinnedViewDefinitions } from './visibility.js';

const header = `-- GENERATED by src/store/clickhouse/view-ddl.ts (yarn clickhouse:views:generate); do not edit by hand.
-- view-ddl.spec.ts checks that this file equals the generated text. The gate's one definition is
-- visibility.ts (pinnedViewDefinitions, pinnedGateTerms), which the API also inlines into its statements.
--
-- Visibility gate views, plan §3.2; WP4 semantics in docs/clickhouse-port/wp4-commit-and-visibility.md,
-- pinned-view parameter contract in docs/clickhouse-port/wp6b-gate-cost.md.
--
-- Two families with the same visibility rule:
--   * <name>_v(node = n)  convenience, for ad-hoc use: computes the watermark, the epoch fence and the
--                         aborted-commit set with subqueries inside every view (2.5–6 ms fixed per query, WP6).
--   * <name>_at(...)      pinned: a pure filter on the row's commit_seq, no subqueries. The reader takes ONE
--                         snapshot (visibility.ts readSnapshot: one query) and passes the same values to every
--                         view of a request, so a query joining views sees one set of commits (no torn reads).
--                         The API reads the same rows with the predicate inlined (inlinePinnedView).
--                         Parameters (all required):
--       node views:     node UInt32, visible UInt64, fence Array(UInt64), void Array(UInt64)
--       node-agnostic:  visible0 UInt64, tail Array(UInt64), fence Array(UInt64), void Array(UInt64)
--     visible  = visible(n); visible0 = visible(0); tail = committed seqs above visible0;
--     fence[e] = for epoch e (1-based, dense up to the snapshot's highest epoch) the highest valid COUNTER
--                (commit_seq & 0xFFFFFFFFFF) of that epoch; 0xFFFFFFFFFF if the epoch is not fenced;
--     void     = the aborted seqs up to the snapshot's highest seq, or [0xFFFFFFFFFFFFFFFF] (overflow sentinel)
--                when there are more than visibility.ts \`voidInlineLimit\`: then the view falls back to the
--                \`commit_void\` subquery. Otherwise that branch is constant-folded away and never runs.
--     The parameters are trusted: they must come from readSnapshot (never from a client request); the views no
--     longer clamp \`visible\` to the live watermark.
--
-- A row is visible iff all of:
--   1. commit_seq <= the watermark (node views: visible(n); node-agnostic: visible(0), or the commit is
--      'committed' above it: the committed tail, so a stalled save on one network hides nothing elsewhere);
--   2. commit_seq is not void (cg.commit_void: aborted commits, including those aborted by recovery);
--   3. commit_seq is not fenced: epoch = commit_seq >> 40; if the epoch has a fence (it is older than the
--      current lease) then commit_seq <= its max_valid_seq. fence_max_seq is dense from epoch 1.
-- Membership views then collapse signs: GROUP BY key HAVING sum(sign) > 0.
-- A missing visibility row means watermark 0 (nothing visible). Querying a node view without \`node\` fails.
-- Non-key columns of collapsed rows use any() (+1/-1 rows carry identical values) or
-- argMaxIf(..., version, sign > 0) for per-acceptance timestamps.
-- Views are CREATE OR REPLACE so re-applying picks up amendments.
`;

const fenceWith = `WITH
    (SELECT arrayMap(t -> t.2, arraySort(groupArray((epoch, max_valid_seq))))
     FROM (SELECT epoch, min(max_valid_seq) AS max_valid_seq FROM cg.epoch_fence GROUP BY epoch)) AS fence_max_seq`;

/** The `*_v` gate: watermark, void set and fence read by subqueries. */
const convenienceGateTerms = (kind: PinnedViewDefinition['kind']) => [
  ...(kind === 'node'
    ? [
        'node_internal_id = {node:UInt32}',
        'commit_seq <= (SELECT max(visible_seq) FROM cg.visibility WHERE node_internal_id = {node:UInt32})',
      ]
    : [
        `(commit_seq <= (SELECT max(visible_seq) FROM cg.visibility WHERE node_internal_id = 0)
       OR commit_seq IN (SELECT commit_seq FROM cg.commit_log
                         WHERE state = 'committed' AND commit_seq > (SELECT max(visible_seq) FROM cg.visibility WHERE node_internal_id = 0)))`,
      ]),
  'commit_seq NOT IN (SELECT commit_seq FROM cg.commit_void)',
  `(bitShiftRight(commit_seq, 40) > length(fence_max_seq)
       OR commit_seq <= arrayElement(fence_max_seq, bitShiftRight(commit_seq, 40)))`,
];

const selectList = (definition: PinnedViewDefinition) =>
  definition.groupBy === undefined
    ? ` ${definition.select.join(', ')}`
    : `\n    ${definition.select.join(',\n    ')}`;

/* eslint-disable max-params */
const viewStatement = (
  name: string,
  definition: PinnedViewDefinition,
  terms: readonly string[],
  withClause = ''
) =>
  `CREATE OR REPLACE VIEW cg.${name} AS
${withClause === '' ? '' : `${withClause}\n`}SELECT${selectList(definition)}
FROM cg.${definition.table}
WHERE ${terms.join('\n  AND ')}${
    definition.groupBy === undefined
      ? ''
      : `\nGROUP BY ${definition.groupBy.join(', ')}\nHAVING sum(sign) > 0`
  };`;
/* eslint-enable max-params */

/** `CREATE OR REPLACE VIEW cg.<name>` of one pinned (`*_at`) view. */
export const pinnedViewStatement = (name: string) => {
  const definition = pinnedViewDefinitions[name];
  if (definition === undefined) {
    // eslint-disable-next-line functional/no-throw-statement
    throw new RangeError(`No pinned view ${name}.`);
  }
  return viewStatement(
    name,
    definition,
    pinnedGateTerms(definition.kind, { qualifier: 'cg.' })
  );
};

/** `CREATE OR REPLACE VIEW cg.<base>_v` of a node-scoped or node-agnostic pinned view. */
export const convenienceViewStatement = (name: string) => {
  const definition = pinnedViewDefinitions[name]!;
  return viewStatement(
    `${name.replace(/_at$/u, '')}_v`,
    definition,
    convenienceGateTerms(definition.kind),
    fenceWith
  );
};

const nodeView = `CREATE OR REPLACE VIEW cg.node_v AS
SELECT internal_id, name, protocol_version, user_agent, first_connected_at, latest_connection_began_at
FROM cg.node FINAL;`;

/** The text of ddl/050_views.sql. */
export const viewsDdl = () => {
  const names = Object.keys(pinnedViewDefinitions);
  const pair = (name: string) => {
    const { comment } = pinnedViewDefinitions[name]!;
    const prefix = comment === undefined ? '' : `-- ${comment}\n`;
    return `${prefix}${convenienceViewStatement(
      name
    )}\n\n${prefix}${pinnedViewStatement(name)}`;
  };
  return `${header}\n${[
    nodeView,
    ...names
      .filter((name) => pinnedViewDefinitions[name]!.kind === 'node')
      .map(pair),
    `-- Node-agnostic views (no acceptance fields; checklist item 7: their names carry no node).`,
    ...names
      .filter((name) => pinnedViewDefinitions[name]!.kind === 'agnostic')
      .map(pair),
  ].join('\n\n')}\n`;
};

/** The pinned views defined outside 050 (with the tables they read), by DDL file. */
export const viewsOutside050: readonly (readonly [
  string,
  readonly string[]
])[] = [
  ['070_spend.sql', ['spend_at']],
  ['080_authchain.sql', ['authchain_link_at']],
];
